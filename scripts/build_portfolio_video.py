    def font(self, size, bold=False):
        return ImageFont.truetype(str(self.bold if bold else self.regular), size)

    def text(self, d, xy, text, size, color=WHITE, bold=False):
        d.text(xy, text, font=self.font(size, bold), fill=color, stroke_width=0)

    def wrap(self, d, xy, text, width, size, color=MUTED, spacing=12):
        x, y = xy
        row = ''
        font = self.font(size)
        for char in text:
            if row and d.textlength(row+char, font=font) > width and char not in '，。；：！？、）】':
                d.text((x, y), row, font=font, fill=color)
                y += size+spacing
                row = ''
            row += char
        if row:
            d.text((x, y), row, font=font, fill=color)
        return y+size+spacing

