def mix_audio(events, source_dir, destination, duration, capture_start):
    audio = np.zeros((round(duration*RATE), 2), dtype=np.float32)
    assets = {}
    cache = {}
    for event in events:
        name = event['asset']
        if name not in cache:
            path = source_dir/f'{name}.wav'
            require(path.is_file(), f'original audio asset missing: {name}')
            with wave.open(str(path), 'rb') as w:
                require(w.getsampwidth() == 2 and w.getnchannels() in (1, 2), 'only original PCM16 mono/stereo WAV supported')
                rate, channels = w.getframerate(), w.getnchannels()
                raw = np.frombuffer(w.readframes(w.getnframes()), dtype='<i2').reshape(-1, channels).astype(np.float32)/32768
            if channels == 1:
                raw = np.repeat(raw, 2, axis=1)*np.float32(.70710678)
            if rate != RATE:
                old_t = np.arange(len(raw))/rate
                new_t = np.arange(round(len(raw)*RATE/rate))/RATE
                raw = np.column_stack([np.interp(new_t, old_t, raw[:, c]) for c in range(2)]).astype(np.float32)
            cache[name] = raw
            assets[name] = {'path': str(path.resolve()), 'sha256': sha(path), 'bytes': path.stat().st_size,
                            'sourceSampleRate': rate, 'sourceChannels': channels}
        start = round((INTRO+max(0, event['videoSeconds']-capture_start))*RATE)
        clip = cache[name]
        count = min(len(clip), len(audio)-start)
        require(count > 0, 'audio event falls outside final film')
        audio[start:start+count] += clip[:count]*np.float32(event['volume']*.5)
    peak = float(np.max(np.abs(audio)))
    gain = min(1.0, .82/peak) if peak else 1.0
    pcm = np.rint(audio*gain*32767).astype('<i2')
    with wave.open(str(destination), 'wb') as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(pcm.tobytes())
    return {'eventCount': len(events), 'assets': assets, 'sourceGain': .5, 'peakBeforeNormalization': peak,
            'normalizationGain': gain, 'stereoMethod': 'centered source channels; no invented spatial attenuation',
            'sampleRate': RATE, 'channels': 2, 'sha256': sha(destination),
            'method': 'genuine engine-triggered events remixed from original WAVs; not loopback capture'}


def run(command, log):
    with Path(log).open('w', encoding='utf-8') as f:
        result = subprocess.run([str(x) for x in command], stdout=f, stderr=subprocess.STDOUT, timeout=2400)
    require(result.returncode == 0, f'ffmpeg failed; see {log}')


