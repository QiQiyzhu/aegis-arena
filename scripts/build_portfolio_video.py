class Editorial:
    def __init__(self, font_dir, preview, has_audio=False):
        self.regular = Path(font_dir)/'msyh.ttc'
        self.bold = Path(font_dir)/'msyhbd.ttc'
        require(self.regular.is_file() and self.bold.is_file(), 'Microsoft YaHei fonts unavailable')
        self.preview = preview
