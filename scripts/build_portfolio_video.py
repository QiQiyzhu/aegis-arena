def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def strict_json(path):
    def pairs(rows):
        result = {}
        for key, value in rows:
            if key in result:
                raise ValueError(f'duplicate JSON key: {key}')
            result[key] = value
        return result
    return json.loads(Path(path).read_text(encoding='utf-8-sig'), object_pairs_hook=pairs,
                      parse_constant=lambda x: (_ for _ in ()).throw(ValueError(f'non-finite JSON: {x}')))


def finite(value, label):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError(f'{label} must be finite')
    return float(value)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def validate_capture(capture, preview=False):
    require(capture.get('validRun') is True, 'capture did not pass native completion')
    require(capture.get('scriptedPlayer') is True and capture.get('fixtureDamage') is False
            and capture.get('humanPlaytest') is False, 'unsupported input/provenance flags')
    require(capture.get('outcome') in ('won', 'lost'), 'capture has no natural outcome')
    rows = capture.get('frameTimes', [])
    require(len(rows) >= 2 and capture.get('frames') == len(rows) == capture.get('completedFrames'),
            'missing or incomplete native frames')
    times = [finite(row['videoSeconds'], 'frame time') for row in rows]
    require(times[0] >= 0, 'negative frame time')
    deltas = [b-a for a, b in zip(times, times[1:])]
    require(all(d > 0 for d in deltas), 'frame times are not strictly increasing')
    interval = deltas[0]
    require(all(abs(d-interval) < 1e-5 for d in deltas), 'native frame intervals are irregular')
    if not preview:
        require(abs(interval - 1/FPS) < 1e-5, 'final film requires native 1/30 second frame spacing')
    else:
        require(abs(interval*FPS-round(interval*FPS)) < 1e-4, 'preview interval must map exactly to 30 fps')
    for index, row in enumerate(rows):
        require(row['file'] == f'frame-{index:06d}.png', 'frame order/path is not canonical')
        finite(row['worldSeconds'], 'world time')
    world = [r['worldSeconds'] for r in rows]
    require(all(b+1e-7 >= a for a, b in zip(world, world[1:])), 'world time runs backwards')
    # Pauses may freeze world time, but the film clock continues at native cadence.
    require(all((b-a) <= interval+1e-4 for a, b in zip(world, world[1:])), 'world time exceeds capture cadence')
    samples = capture.get('samples', [])
    require(samples, 'missing actual phase samples')
    sample_times = [finite(s['videoSeconds'], 'sample time') for s in samples]
    require(all(b >= a for a, b in zip(sample_times, sample_times[1:])), 'sample clock runs backwards')
    for s in samples:
        require(s.get('phase') in range(5) and s.get('wave') in range(4), 'unknown native phase/wave')
        require(isinstance(s.get('diagnostics'), bool), 'missing diagnostic state')
    audio = capture.get('audioEvents', [])
    require(preview or bool(audio), 'final film requires genuine engine audioEvents')
    previous = -1.0
    for event in audio:
        t = finite(event['videoSeconds'], 'audio time')
        require(previous <= t <= times[-1]+interval+.1 and t >= 0, 'audio event clock is invalid')
        previous = t
        require(re.fullmatch(r'S_[A-Za-z0-9_]+', event['asset']) is not None, 'unsafe sound asset name')
        require(0 <= finite(event['volume'], 'sound volume') <= 4, 'invalid sound volume')
        require(len(event['location']) == 3, 'missing actual sound location')
        for coordinate in event['location']:
            finite(coordinate, 'sound location')
        finite(event['worldSeconds'], 'audio world time')
    return interval


def chapter_key(sample):
    phase, stage = sample['phase'], sample['wave']
    if phase == 0:
        return 'briefing'
    if phase in (3, 4):
        return 'result'
    if phase == 2:
        return f'upgrade{stage}'
    if sample['diagnostics']:
        return 'diagnostics'
    return f'stage{stage}'


def validate_ledger(ledger, capture):
    require(ledger.get('ledgerBalanced') is True and ledger.get('traceComplete') is True
            and ledger.get('completed') is True, 'system ledger is incomplete')
    require(ledger['outcome'] == capture['outcome'], 'system and capture outcomes disagree')
    integer_fields = ('energyInitial','energyFinal','energyEarned','energySpent','energyOverflow',
                      'pulsesUsed','repairsUsed','enemiesRewarded','stagesRewarded','eventCount','upgradeMask')
    for key in integer_fields:
        require(type(ledger.get(key)) is int and ledger[key] >= 0, f'invalid ledger counter: {key}')
    for key in ('trialElapsedSeconds','repairPlayerActualHealing','repairCompanionActualHealing',
                'alliedActualDamageDealt','playerActualDamageTaken','companionActualDamageTaken'):
        require(finite(ledger[key], key) >= 0, f'negative ledger value: {key}')
    require(ledger['energyInitial']+ledger['energyEarned']-ledger['energySpent']==ledger['energyFinal'], 'unbalanced energy ledger')
    require(ledger['energySpent']==ledger['pulsesUsed']*35+ledger['repairsUsed']*40, 'spend does not match actual actions')
    require(ledger['energyEarned']+ledger['energyOverflow']==ledger['enemiesRewarded']*12+ledger['stagesRewarded']*25,
            'income does not match kill and stage rewards')
    require(0 <= ledger['energyFinal'] <= 100 and 0 <= ledger['stagesRewarded'] <= 3, 'invalid resource/stage range')
    require(capture['outcome'] != 'won' or ledger['stagesRewarded'] == 3, 'won without three completed stages')


def chapters(capture, interval):
    rows, samples = capture['frameTimes'], capture['samples']
    times = [s['videoSeconds'] for s in samples]
    result = []
    # Decide changes on actual source frames. One source frame always remains one
    # source frame in final mode; sparse previews are explicitly duplicated.
    for i, row in enumerate(rows):
        sample = samples[max(0, bisect_right(times, row['videoSeconds'])-1)]
        key = chapter_key(sample)
        if not result or result[-1]['key'] != key:
            result.append({'key': key, 'firstSourceFrame': i, 'start': i*interval})
    duration = len(rows)*interval
    for i, chapter in enumerate(result):
        chapter['duration'] = (result[i+1]['start'] if i+1 < len(result) else duration)-chapter['start']
    return result


